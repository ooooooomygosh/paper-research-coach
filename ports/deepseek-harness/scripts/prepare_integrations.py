"""Adapt the vendored standalone renderer without running its CLI or updater."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
ANSWER = ROOT / "integrations/answer-me-with-html"
source = (ANSWER / "skills/answer-me-with-html/scripts/am.mjs").read_text(encoding="utf-8")
marker = "// bin/am.js\n"
assert source.count(marker) == 1
body, cli = source.split(marker)
if body.startswith("#!"):
    body = body.split("\n", 1)[1]
licenses = cli[cli.index("/*!"):]
for declaration, statement in (
    ("function readImage(ref, baseDir) {", 'throw new ImageError("Paper Research Coach 只接受内联图片，不读取草稿指定的本机图片。", ref);'),
    ("function readSlice(ref, range, baseDir) {", 'throw new CodeError("Paper Research Coach 不从草稿路径读取本机代码；请直接写入代码内容。");'),
):
    assert body.count(declaration) == 1, declaration
    body = body.replace(declaration, declaration + "\n  " + statement)
for declaration in ("function renderDoc(", "async function loadMath("):
    assert declaration in body, declaration
output = "// PRC integration: CLI disabled; local-file embedding disabled. Original source and license retained.\n" + body
output += "\nexport { renderDoc, loadMath };\n" + licenses
(ANSWER / "prc-renderer.mjs").write_text(output, encoding="utf-8")
learning = ROOT / "integrations/learn-from-materials"
page_source = (learning / "scripts/render_page.py").read_text(encoding="utf-8")
old = 'if not rules and meta.get("learningDepth") != "quick":'
new = 'if not rules and meta.get("learningDepth") != "quick" and ("methodLibrary" not in data or any(m.get("kind") == "rule" for m in data["methodLibrary"]["methods"])):'
assert page_source.count(old) == 1
(learning / "scripts/prc_render_page.py").write_text(
    '# PRC adaptation: do not invent action rules when canonical methods contain none.\n' + page_source.replace(old, new), encoding="utf-8")
extractor = (learning / "scripts/extractor/utils.py").read_text(encoding="utf-8")
start = extractor.index('    elif ext == ".pdf":\n')
stop = extractor.index('    elif ext in TEXT_EXTENSIONS:', start)
pdf_branch = '''    elif ext == ".pdf":
        # PRC uses the same packaged PDFium engine as the paper reader. In
        # particular it decodes CJK CID fonts that the legacy fallback loses.
        import pypdfium2 as pdfium
        print(f"Extracting PDF with bundled PDFium: {input_str}")
        try:
            with pdfium.PdfDocument(input_str) as document:
                pages = len(document)
                parts = []
                for page_index in range(pages):
                    page = document[page_index]
                    try:
                        text_page = page.get_textpage()
                        try:
                            parts.append(text_page.get_text_range().replace("\\r\\n", "\\n"))
                        finally:
                            text_page.close()
                    finally:
                        page.close()
            text = "\\f".join(parts)
        except Exception as error:
            raise ExtractionError("PDF text could not be read by the bundled engine: " + str(error)) from error
        if not text.strip():
            raise ExtractionError("PDF has no readable text layer. Perform OCR separately before importing scanned pages.")
        method = "pypdfium2"
        pages_label = "pages"
        ocr_recommended = any(not part.strip() for part in parts)
        visual_review_recommended = True
'''
(learning / "scripts/extractor/prc_utils.py").write_text(
    "# PRC adaptation: original extractor pipeline with packaged PDFium text/page extraction.\n" + extractor[:start] + pdf_branch + extractor[stop:], encoding="utf-8")
(ROOT / "integrations/SOURCES.json").write_text(json.dumps({
    "learn-from-materials": {"url": "https://github.com/dmoshehun-prog/learn-from-materials", "commit": "f8849746d85c5ebe8556fdb8f388783ac7483c8b", "license": "MIT", "version": "1.1.0", "adaptation": "scripts/prc_render_page.py and scripts/extractor/prc_utils.py are generated by scripts/prepare_integrations.py"},
    "answer-me-with-html": {"url": "https://github.com/QingYunA/answer-me-with-html", "commit": "406ef8dd72386de1ae2e2b483d40ce9625043e78", "license": "MIT", "version": "0.5.10", "adaptation": "prc-renderer.mjs is generated by scripts/prepare_integrations.py"}
}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print("Pinned renderer prepared; no separate CLI, login or package install required.")
